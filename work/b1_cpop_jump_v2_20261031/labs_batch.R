args<-commandArgs(trailingOnly=TRUE)
stopifnot(length(args)==3L)
source(args[1],local=TRUE)
input<-read.csv(args[2])
result<-lapply(split(input,input$case_id),function(d){
  tic<-proc.time()[['elapsed']]
  tryCatch({
    fit<-labs_sic_fast(d$y,initial_test=TRUE,M=5L,retest_M=2L,multipliers=seq(.50,1.50,.05),alpha=1.01)
    stopifnot(length(fit$fit)==nrow(d),all(is.finite(fit$fit)))
    data.frame(case_id=d$case_id,index=d$index,fitted=fit$fit,knots=length(fit$cpts),
                seconds=proc.time()[['elapsed']]-tic,status='ok',error='')
  },error=function(e)data.frame(case_id=d$case_id[1],index=0,fitted=NA_real_,knots=0,
      seconds=proc.time()[['elapsed']]-tic,status='unavailable',error=conditionMessage(e)))
})
write.csv(do.call(rbind,result),args[3],row.names=FALSE)
writeLines(capture.output(sessionInfo()),paste0(args[3],'.session.txt'))
