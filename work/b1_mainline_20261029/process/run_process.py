def digest(path): return hashlib.sha256(Path(path).read_bytes()).hexdigest()

def shape(seed,mech):
    rng=np.random.default_rng(seed+{'none':0,'step':31,'partial':61,'slow':91,
                                  'early_exit':121,'dropout':151,'curved':181,'multiplateau':211}[mech])
    d=float(rng.uniform(1,4)); level=float(rng.uniform(1.4,1.6));release=float(rng.uniform(1,3))
    if mech=='none': return dict(knots=[-15,45],values=[0,0],curved=False)
    ramp=float(rng.uniform(3,6))
    if mech=='step': ramp=.15
    if mech=='partial': level=float(rng.uniform(.65,1.1))
    if mech=='slow': ramp=float(rng.uniform(9,14))
    end=30.
    if mech=='early_exit': end=float(rng.uniform(17,24))
    knots=[-15,d,d+ramp,end,end+release,45]
    values=[0,0,level,level,0,0]
    if mech=='dropout':
        g=float(rng.uniform(15,18))
        knots=[-15,d,d+ramp,g,g+.2,g+4,g+4.2,30,30+release,45]
        values=[0,0,level,level,0,0,level,level,0,0]
    if mech=='multiplateau':
        knots=[-15,d,d+ramp,13,16,22,25,30,30+release,45]
        values=[0,0,.6,.6,1.45,1.45,.85,.85,0,0]
    return dict(knots=knots,values=values,curved=mech=='curved')

def truth_average(sh,s,e):
    """Exact integral of linear or quadratic pieces, splitting at DGP knots."""
    ks=np.asarray(sh['knots']);vs=np.asarray(sh['values']);out=np.zeros(len(s))
    for a,b,ya,yb in zip(ks[:-1],ks[1:],vs[:-1],vs[1:]):
        lo=np.clip(s,a,b);hi=np.clip(e,a,b)
        z0=(lo-a)/(b-a);z1=(hi-a)/(b-a)
        if sh['curved'] and ya==0 and yb>0:
            integral=(b-a)*yb*(z1**3-z0**3)/3
        elif sh['curved'] and ya>0 and yb==0:
            # Quadratic release, deliberately outside linear template family.
            integral=(b-a)*ya*((z1-z0)-(z1*z1-z0*z0)+(z1**3-z0**3)/3)
        else: integral=(b-a)*(ya*(z1-z0)+(yb-ya)*(z1*z1-z0*z0)/2)
        out+=integral
    return out/(e-s)

def features(y,delta):
    s=np.arange(-15,45-1e-8,delta)
    t=np.r_[s,s[-1]+delta]*60
    result=f0.extract(t,np.full(len(s),3.),3-np.asarray(y),t0=0,t1=1800,q=1.5,
                      dwell_samples=max(1,int(np.ceil(.5/delta-1e-9))))
    to_value=lambda key: None if result[key] is None else float(result[key][1])
    return dict(onset_s=to_value('onset_interval_s'),target_s=to_value('target_interval_s'),
                recovery_s=result['power_recovery_time_s'],stage=result['stage'])

def assess(pred,truth,y,delta,meta,method,seconds,extra=None):
    s=np.arange(-15,45-1e-8,delta);mask=(s>=-1e-9)&(s<30-1e-9)
    a,b=features(pred,delta),features(truth,delta)
    result=dict(**meta,method=method,seconds=seconds,
                curve_rmse=float(np.sqrt(np.mean((pred-truth)**2))),
                request_rmse=float(np.sqrt(np.mean((pred[mask]-truth[mask])**2))),
                eta_raw=float(np.sum(y[mask]*delta)/(1.5*30)),
                eta_truth=float(np.sum(truth[mask]*delta)/(1.5*30)),
                stage_hat=a['stage'],stage_truth=b['stage'],stage_correct=a['stage']==b['stage'],
                physical_timing_status='not_identified_by_this_observation_feature_comparison')
    result['eta_abs_error_pp']=100*abs(result['eta_raw']-result['eta_truth'])
    for key in ('onset_s','target_s','recovery_s'):
        ah,bh=a[key],b[key]
        result[key]=ah;result[key+'_truth']=bh
        result[key+'_joint_valid']=ah is not None and bh is not None
        result[key+'_abs_error']=abs(ah-bh) if ah is not None and bh is not None else None
        result[key+'_false_positive']=ah is not None and bh is None
        result[key+'_miss']=ah is None and bh is not None
    if extra:result.update(extra)
    return result

def ride_fit(y,delta,sigma):
    s=np.arange(-15,45-1e-8,delta);e=s+delta
    event=EventInput(s=s,e=e,r=y,q=1.5,W=30,obs_end=45,a_max=1.5,b_max=1,
                     sigma=sigma,sB=0,delta=delta,is_ev=1,event_id=0)
    # No simulator parameter labels or model-selection oracle is supplied.
    out=identify_event(event,structures=(0,1,2),n_starts=3,ci_method='none',
                       lr_crit=None,seed=711)
    if not out['A_hat']:return np.zeros(len(y)),dict(ride_structure=0)
    theta=np.array([out[f'th_{key}'] for key in PARAM_NAMES_M2])
    pred=1.5*interval_average(np.asarray(theta),30,s,e)
    return pred,dict(ride_structure=int(out.get('struct',out.get('structure',1))))

def prepare(mode):
    protocol=json.loads((ROOT/'protocol.json').read_text(encoding='utf-8'))
    seeds=protocol['seeds_development'] if mode=='pilot' else protocol['seeds_main']
    directory=ROOT/mode
    directory.mkdir(exist_ok=True)
    if (directory/'prepared.json').exists():raise RuntimeError('Existing prepared run is immutable; do not overwrite')
    rows,arrays,info,cpop_rows=[],{},[],[]
    t0=time.perf_counter();event_id=0
    for rep,seed in enumerate(seeds):
        for mech in protocol['mechanisms']:
            sh=shape(seed,mech)
            for delta in protocol['delta_minutes']:
                s=np.arange(-15,45-1e-8,delta);e=s+delta
                mu=truth_average(sh,s,e)
                rng=np.random.default_rng(seed+event_id*13+1729)
                z=rng.normal(size=len(s))
                for sigma in protocol['sigma_kw']:
                    y=mu+sigma*z
                    meta=dict(event_id=event_id,rep=rep,seed=seed,mechanism=mech,delta_min=delta,sigma_kw=sigma)
                    arrays[f'{event_id}_truth']=mu;arrays[f'{event_id}_y']=y
                    info.append(meta)
                    for method,fun in (
                        ('F0_frozen_rule',lambda:(y.copy(),{})),
                        ('F1_frozen_segment_adapter',lambda:original_f1(y,delta,sigma)),
                        ('Grid_point',lambda:fit(y,delta,sigma,False)),
                        ('Grid_average',lambda:fit(y,delta,sigma,True)),
                        ('RIDE_template_average',lambda:ride_fit(y,delta,sigma))):
                        tic=time.perf_counter();pred,extra=fun();elapsed=time.perf_counter()-tic
                        arrays[f'{event_id}_{method}']=pred
                        rows.append(assess(pred,mu,y,delta,meta,method,elapsed,extra))
                    for x,v in zip((s+e)/2,y):cpop_rows.append(dict(event_id=event_id,x=x,y=v,sigma=sigma))
                    event_id+=1
            print(f'{mode} rep {rep+1}/{len(seeds)} {mech}: {event_id} variants, {time.perf_counter()-t0:.1f}s',flush=True)
    np.savez_compressed(directory/'curves.npz',**arrays)
    pd.DataFrame(rows).to_csv(directory/'python_metrics.csv',index=False,encoding='utf-8')
    pd.DataFrame(cpop_rows).to_csv(directory/'cpop_input.csv',index=False,encoding='utf-8')
    (directory/'events.json').write_text(json.dumps(info,ensure_ascii=False,indent=2),encoding='utf-8')
    receipt=dict(mode=mode,n_variants=event_id,n_python_metrics=len(rows),elapsed_seconds=time.perf_counter()-t0,
                 protocol_sha256=digest(ROOT/'protocol.json'),source_sha256={f:digest(ROOT/f) for f in ['models.py','run_process.py','cpop_batch.R']},
                 nature='simulation; paired variants; no real data')
    (directory/'prepared.json').write_text(json.dumps(receipt,ensure_ascii=False,indent=2),encoding='utf-8')

def integrate_segments(segments,s,e):
    result=np.zeros(len(s));coverage=np.zeros(len(s))
    # The original package anchors the left endpoint at the first data midpoint.
    # Extend its first straight segment through the half-bin to the meter edge;
    # this is the same linear function, not a refit or an extra parameter.
    for j,row in enumerate(segments.itertuples()):
        left=min(row.x0,float(s[0])) if j==0 else row.x0
        right=max(row.x1,float(e[-1])) if j==len(segments)-1 else row.x1
        lo=np.maximum(s,left);hi=np.minimum(e,right)
        width=np.maximum(0,hi-lo)
        result+=width*(row.gradient*(hi+lo)/2+row.intercept)
        coverage+=width
    if not np.allclose(coverage,e-s,atol=1e-7):raise ValueError('CPOP fit does not cover observation intervals')
    return result/(e-s)

def finalize(mode,output_subdir=None):
    input_directory=ROOT/mode
    directory=input_directory if output_subdir is None else input_directory/output_subdir
    directory.mkdir(exist_ok=True)
    if (directory/'summary.json').exists():raise RuntimeError('Do not overwrite finalized output')
    native=pd.read_csv(input_directory/'cpop_segments.csv')
    rows=pd.read_csv(input_directory/'python_metrics.csv').to_dict('records')
    arrays=dict(np.load(input_directory/'curves.npz'))
    events=json.loads((input_directory/'events.json').read_text(encoding='utf-8'))
    for meta in events:
        i=meta['event_id'];delta=meta['delta_min'];s=np.arange(-15,45-1e-8,delta)
        sub=native[native.event_id==i]
        if sub.empty:raise ValueError(f'no native CPOP result {i}')
        pred=integrate_segments(sub,s,s+delta);arrays[f'{i}_CPOP_original_R']=pred
        extra=dict(native_cost=float(sub.native_cost.iloc[0]),knots_count=len(sub)-1,
                   cpop_left_linear_extension_minutes=max(0,float(sub.x0.iloc[0])-float(s[0])))
        rows.append(assess(pred,arrays[f'{i}_truth'],arrays[f'{i}_y'],delta,meta,'CPOP_original_R',None,extra))
    df=pd.DataFrame(rows)
    # Canonicalize the same nominal resolution after CSV-vs-JSON round trips.
    # 1/6 minute otherwise appears as two adjacent float grouping keys.
    df['delta_min']=df['delta_min'].round(10)
    df.to_csv(directory/'all_metrics.csv',index=False,encoding='utf-8')
    np.savez_compressed(directory/'all_curves.npz',**arrays)
    summaries=[]
    for key,g in df.groupby(['method','delta_min']):
        row=dict(method=key[0],delta_min=key[1],n=len(g),request_rmse=g.request_rmse.mean(),
                 curve_rmse=g.curve_rmse.mean(),stage_accuracy=g.stage_correct.mean(),eta_mae_pp=g.eta_abs_error_pp.mean())
        for feature in ('onset_s','target_s','recovery_s'):
            row[feature+'_mae']=g[feature+'_abs_error'].mean()
            row[feature+'_n_joint_valid']=g[feature+'_joint_valid'].sum()
            row[feature+'_n_true']=g[feature+'_truth'].notna().sum()
            row[feature+'_false_positive']=g[feature+'_false_positive'].sum()
            row[feature+'_miss']=g[feature+'_miss'].sum()
        summaries.append(row)
    table=pd.DataFrame(summaries);table.to_csv(directory/'summary.csv',index=False)
    # Pair all methods on each observation variant; inference over independent seeds.
    base=df.pivot(index=['rep','mechanism','delta_min','sigma_kw'],columns='method',values='request_rmse')
    paired=[]
    for comparator in ['Grid_point','CPOP_original_R','F0_frozen_rule','F1_frozen_segment_adapter','RIDE_template_average']:
        for delta in sorted(df.delta_min.unique()):
            sub=base.xs(delta,level='delta_min')
            differences=(sub['Grid_average']-sub[comparator]).groupby(level='rep').mean()
            se=float(differences.std(ddof=1)/np.sqrt(len(differences)))
            paired.append(dict(candidate='Grid_average',comparator=comparator,delta_min=delta,
                               independent_blocks=len(differences),mean_difference=float(differences.mean()),
                               mc_se=se,mc95_low=float(differences.mean()-2.093*se),mc95_high=float(differences.mean()+2.093*se),
                               wins_blocks=int((differences<0).sum()),scope='mean request RMSE; paired seed-block t19 interval for main, descriptive for pilot'))
    pd.DataFrame(paired).to_csv(directory/'paired.csv',index=False)
    mechanism=df.groupby(['method','mechanism','delta_min']).agg(request_rmse=('request_rmse','mean'),n=('event_id','size')).reset_index()
    mechanism.to_csv(directory/'mechanism_summary.csv',index=False)
    # Shared energy must agree across all methods, and no method output may vanish.
    assert df.groupby('event_id').size().eq(6).all()
    # CSV float round-tripping can differ by machine epsilon from freshly
    # evaluated native metrics; the shared raw integral must agree numerically.
    eta_range=df.groupby('event_id').eta_raw.agg(lambda v:v.max()-v.min())
    assert float(eta_range.max())<1e-12
    assert np.isfinite(df.request_rmse).all()
    result=dict(n_variants=len(events),n_methods=6,n_metric_rows=len(df),independent_blocks=df.rep.nunique(),
                all_outputs_finite=True,common_raw_energy_agrees_at_1e12=True,
                common_raw_energy_max_range=float(eta_range.max()),protocol_sha256=digest(ROOT/'protocol.json'),
                all_metrics_sha256=digest(directory/'all_metrics.csv'),cpop_segments_sha256=digest(input_directory/'cpop_segments.csv'))
    (directory/'summary.json').write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf-8')
    print(table.to_string(index=False));print(pd.DataFrame(paired).to_string(index=False))

