def insert_paragraph_after(paragraph, text="", style=None):
    new_p = OxmlElement("w:p")
    paragraph._p.addnext(new_p)
    new_para = Paragraph(new_p, paragraph._parent)
    if style:
        new_para.style = style
    if text:
        new_para.add_run(text)
    return new_para


def delete_paragraph(paragraph):
    element = paragraph._element
    element.getparent().remove(element)
    paragraph._p = paragraph._element = None


def set_east_asia_font(paragraph, font_name="宋体", size_pt=12):
    for run in paragraph.runs:
        run.font.name = font_name
        run._element.get_or_add_rPr().get_or_add_rFonts().set(qn("w:eastAsia"), font_name)
        if paragraph.style.name == "Normal":
            run.font.size = Pt(size_pt)


def insert_content_after_heading(heading, content):
    anchor = heading
    for kind, text in content:
        if kind == "h2":
            style = "Heading 2"
        else:
            style = "Normal"
        anchor = insert_paragraph_after(anchor, text, style=style)
        set_east_asia_font(anchor)
        if kind == "p":
            anchor.paragraph_format.first_line_indent = Pt(24)
            anchor.paragraph_format.space_after = Pt(6)
            anchor.paragraph_format.line_spacing = 1.25
    return anchor


def replace_between_heading1(doc, start_title_or_prefix, end_title_or_prefix, content, exact_start=False):
    start = None
    end = None
    for idx, para in enumerate(doc.paragraphs):
        text = para.text.strip()
        style_name = para.style.name if para.style is not None else ""
        if style_name == "Heading 1":
            start_match = text == start_title_or_prefix if exact_start else text.startswith(start_title_or_prefix)
            if start_match:
                start = idx
            elif start is not None:
                end_match = text == end_title_or_prefix if end_title_or_prefix in ("ABSTRACT", "目录", "参考文献") else text.startswith(end_title_or_prefix)
                if end_match:
                    end = idx
                    break
    if start is None or end is None:
        raise SystemExit(f"Could not locate section: {start_title_or_prefix}")
    heading = doc.paragraphs[start]
    for para in list(doc.paragraphs[start + 1 : end]):
        delete_paragraph(para)
    insert_content_after_heading(heading, content)


